#!/bin/bash
# can_persist.sh - give the two Piper CAN adapters stable names and bring
# them up at 1 Mbit/s on every boot and replug. Run once with sudo.
#
# can0/can1 are kernel enumeration order, so a reboot or a USB port swap can
# swap the arms. The rules below pin each name to the adapter's USB serial
# (read from sysfs on 2026-10-06, when can0 = Piper 1 and can1 = Piper 2).
# Then point the configs at the new names:
#   sed -i 's/"can0"/"can_piper1"/' real_robot/configs/piper_1.json
#   sed -i 's/"can1"/"can_piper2"/' real_robot/configs/piper_2.json
#
# Simpler than WeGo's install_can_persist.sh: no ~/piper_config.json, and it
# never touches the arms' leader/follower mode.
#
# Usage:
#   sudo bash real_robot/can_persist.sh            # install
#   sudo bash real_robot/can_persist.sh uninstall  # remove
set -eu

[ "$(id -u)" -eq 0 ] || { echo "Run with sudo"; exit 1; }

RULES=/etc/udev/rules.d/80-piper-can.rules
UNIT=/etc/systemd/system/piper-can-up.service
NAMES="can_piper1 can_piper2"

if [ "${1:-}" = "uninstall" ]; then
    systemctl disable piper-can-up.service 2>/dev/null || true
    rm -f "$RULES" "$UNIT"
    systemctl daemon-reload
    udevadm control --reload-rules
    echo "Removed. Names revert to can0/can1 after a replug or reboot."
    exit 0
fi

cat > "$RULES" <<'EOF'
# Piper CAN adapters (gs_usb, 1d50:606f), pinned by USB serial.
# Generated by research_vla/real_robot/can_persist.sh.
SUBSYSTEM=="net", ACTION=="add", ATTRS{idVendor}=="1d50", ATTRS{idProduct}=="606f", ATTRS{serial}=="003D002F5246570620323934", NAME="can_piper1"
SUBSYSTEM=="net", ACTION=="add", ATTRS{idVendor}=="1d50", ATTRS{idProduct}=="606f", ATTRS{serial}=="002200425443570A20393433", NAME="can_piper2"
# add|move: the rename emits a "move" event that replaces the device's udev
# record, so a rule matching only "add" loses SYSTEMD_WANTS on replug.
SUBSYSTEM=="net", ACTION=="add|move", ATTRS{idVendor}=="1d50", ATTRS{idProduct}=="606f", TAG+="systemd", ENV{SYSTEMD_WANTS}+="piper-can-up.service"
EOF

cat > "$UNIT" <<EOF
[Unit]
Description=Bring up Piper CAN interfaces at 1 Mbit/s

[Service]
Type=oneshot
ExecStart=/bin/sh -c 'for i in $NAMES; do ip link show \$i >/dev/null 2>&1 || continue; ip link set \$i down; ip link set \$i type can bitrate 1000000; ip link set \$i up; done'

[Install]
WantedBy=multi-user.target
EOF

systemctl daemon-reload
systemctl enable piper-can-up.service
udevadm control --reload-rules

# Rename now without a replug: retrigger the adapters' net devices.
for i in can0 can1 $NAMES; do ip link set "$i" down 2>/dev/null || true; done
udevadm trigger --subsystem-match=net --property-match=ID_NET_DRIVER=gs_usb --action=add
udevadm settle
systemctl start piper-can-up.service
ip -br link show type can
